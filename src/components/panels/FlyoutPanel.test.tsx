import { fireEvent, render, screen } from '@testing-library/react'
import { expect, it, vi } from 'vitest'
import { FlyoutPanel } from './FlyoutPanel'
it('provides a named Settings dialog, traps Tab and restores its opener on Escape', () => {
  const opener = document.createElement('button')
  document.body.append(opener)
  opener.focus()
  const close = vi.fn()
  const { rerender } = render(<FlyoutPanel manageFocus isOpen onClose={close} title="Settings"><button>Last action</button></FlyoutPanel>)
  const dialog = screen.getByRole('dialog', { name: 'Settings' })
  expect(dialog).toHaveAttribute('aria-modal', 'true')
  const last = screen.getByRole('button', { name: 'Last action' })
  last.focus()
  fireEvent.keyDown(document, { key: 'Tab' })
  expect(screen.getByRole('button', { name: 'Close panel' })).toHaveFocus()
  fireEvent.keyDown(document, { key: 'Escape' })
  expect(close).toHaveBeenCalledTimes(1)
  rerender(<FlyoutPanel manageFocus isOpen={false} onClose={close} title="Settings"><button>Last action</button></FlyoutPanel>)
  expect(opener).toHaveFocus()
  opener.remove()
})

it('yields modality and all keys while a sibling picker owns focus, then resumes without stealing focus', () => {
  const close = vi.fn()
  const { rerender } = render(<FlyoutPanel manageFocus isOpen onClose={close} title="Settings"><button>Action</button></FlyoutPanel>)
  const dialog = screen.getByRole('dialog', { name: 'Settings' })
  const action = screen.getByRole('button', { name: 'Action' })
  action.focus()
  rerender(<FlyoutPanel manageFocus focusSuspended isOpen onClose={close} title="Settings"><button>Action</button></FlyoutPanel>)
  expect(dialog).not.toHaveAttribute('aria-modal', 'true')
  expect(dialog).toHaveAttribute('inert')
  fireEvent.keyDown(document, { key: 'Escape' })
  fireEvent.keyDown(document, { key: 'Tab' })
  expect(close).not.toHaveBeenCalled()
  expect(action).toHaveFocus()
  rerender(<FlyoutPanel manageFocus isOpen onClose={close} title="Settings"><button>Action</button></FlyoutPanel>)
  expect(dialog).toHaveAttribute('aria-modal', 'true')
  expect(dialog).not.toHaveAttribute('inert')
  expect(action).toHaveFocus()
  fireEvent.keyDown(document, { key: 'Escape' })
  expect(close).toHaveBeenCalledOnce()
})

it('leaves ordinary non-managed flyouts without modal semantics or keyboard ownership', () => {
  const close = vi.fn()
  render(<FlyoutPanel isOpen onClose={close} title="History"><button>History action</button></FlyoutPanel>)
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  const action = screen.getByRole('button', { name: 'History action' })
  action.focus()
  fireEvent.keyDown(action, { key: 'Escape' })
  expect(close).not.toHaveBeenCalled()
  expect(action).toHaveFocus()
})

it('continues to yield to a descendant modal for existing nested-control callers', () => {
  const close = vi.fn()
  render(<FlyoutPanel manageFocus isOpen onClose={close} title="Settings"><div role="dialog" aria-modal="true"><button>Nested action</button></div></FlyoutPanel>)
  const nested = screen.getByRole('button', { name: 'Nested action' })
  nested.focus()
  fireEvent.keyDown(nested, { key: 'Tab' })
  fireEvent.keyDown(nested, { key: 'Escape' })
  expect(close).not.toHaveBeenCalled()
  expect(nested).toHaveFocus()
})
